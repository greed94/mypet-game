/// 펫 규칙이 알리는 소리·진동 신호. 무엇을 틀고 얼마나 떨지는 화면 쪽(Sfx)이 정한다.
/// 규칙 코드가 오디오 패키지를 몰라도 되게 신호만 둔다.
enum Cue {
  /// 반가움. 반김, 개인기 성공 뒤. 밤에는 작은 소리(yip)로 바뀐다.
  bark,

  /// 작은 기쁨. 부름에 대답, 공을 보고 신남.
  yip,

  /// 못 알아들음, 시무룩.
  whine,

  /// 졸림, 지쳐서 쉼.
  sigh,

  /// 킁킁. 딴청 피울 때.
  sniff,

  throwBall,
  bounce,
  pickUp,
  drop,

  /// 개인기를 처음 배웠을 때.
  chime,

  /// 밥 먹기.
  crunch,

  /// 하트, 물건 받기.
  pop,
}
